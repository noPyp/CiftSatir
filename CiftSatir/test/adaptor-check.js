// Platform adaptors: YouTube's TextTracks and Netflix's rendered subtitles.
//
// Both adaptors are exercised with simulated players. That proves the parsing,
// language routing and live-capture timing; it does not prove that a specific
// Netflix title renders text instead of bitmap images, which only a real
// account can show.
//
//   node test/adaptor-check.js

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
let failures = 0;

function check(label, actual, expected) {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (!ok) {
    failures += 1;
    console.log('FAIL  ' + label);
    console.log('      expected: ' + JSON.stringify(expected));
    console.log('      actual:   ' + JSON.stringify(actual));
    return;
  }
  console.log('ok    ' + label);
}

function checkTrue(label, value) {
  if (!value) {
    failures += 1;
    console.log('FAIL  ' + label);
    return;
  }
  console.log('ok    ' + label);
}

function makeSandbox(hostname, documentOverride) {
  const sandbox = {
    console,
    setTimeout,
    clearTimeout,
    setInterval,
    clearInterval,
    location: { hostname: hostname },
    document: documentOverride || {
      querySelector: () => null,
      documentElement: { classList: { add() {}, remove() {} } }
    }
  };
  sandbox.self = sandbox;
  sandbox.window = sandbox;

  const context = vm.createContext(sandbox);
  for (const file of [
    'shared/constants.js',
    'shared/stemmer.js',
    'shared/lang-detect.js',
    'shared/sentence-builder.js',
    'shared/parsers.js',
    'shared/cue-model.js',
    'adaptors/registry.js'
  ]) {
    vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
  }

  return {
    context,
    DS: sandbox.DualSub,
    load(file) {
      vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
    }
  };
}

function makeTrack(spec) {
  const listeners = {};
  return {
    language: spec.language || '',
    label: spec.label || '',
    kind: spec.kind || 'subtitles',
    mode: spec.mode || 'disabled',
    cues: (spec.cues || []).map((cue) => ({
      startTime: cue.start,
      endTime: cue.end,
      text: cue.text
    })),
    addEventListener(type, fn) {
      (listeners[type] = listeners[type] || []).push(fn);
    },
    removeEventListener(type, fn) {
      listeners[type] = (listeners[type] || []).filter((item) => item !== fn);
    },
    listenerCount(type) {
      return (listeners[type] || []).length;
    },
    fire(type) {
      for (const fn of (listeners[type] || []).slice()) {
        fn();
      }
    }
  };
}

(async () => {
  /* ================= YouTube ================= */

  const yt = makeSandbox('www.youtube.com');
  yt.load('adaptors/youtube.js');

  const youtube = yt.DS.adaptors.youtube;

  check('YouTube is recognised', youtube.isYouTube(), true);
  check('another site is not YouTube',
    makeSandbox('example.com').DS.adaptors === undefined, true);

  check('karaoke and positioning markup is stripped',
    youtube.cleanText('<c>Hello</c> <00:00:01.000>there{\\an8}'),
    'Hello there');
  check('entities are decoded',
    youtube.cleanText('Tom &amp; Jerry&nbsp;are here'),
    'Tom & Jerry are here');

  const englishTrack = makeTrack({
    language: 'en',
    label: 'English',
    cues: [{ start: 0, end: 2, text: '<c>Hello</c> there.' }]
  });
  const turkishTrack = makeTrack({
    language: 'tr',
    label: 'Türkçe',
    cues: [{ start: 0, end: 2, text: 'Merhaba.' }]
  });
  const frenchTrack = makeTrack({
    language: 'fr',
    label: 'Français',
    cues: [{ start: 0, end: 2, text: 'Bonjour, je veux comprendre chaque mot.' }]
  });

  check('English track is classified as English',
    youtube.kindOf(englishTrack, youtube.cuesOf(englishTrack)), 'en');
  check('Turkish track is classified as Turkish',
    youtube.kindOf(turkishTrack, youtube.cuesOf(turkishTrack)), 'tr');
  check('a French track is refused',
    youtube.kindOf(frenchTrack, youtube.cuesOf(frenchTrack)), null);

  const asrTrack = makeTrack({
    language: 'en',
    label: 'English (auto-generated)',
    kind: 'captions',
    cues: [{ start: 0, end: 2, text: 'rough automatic line' }]
  });
  check('auto-generated label is recognised', youtube.isAutoGenerated(asrTrack), true);

  const ytVideo = {
    textTracks: [asrTrack, englishTrack, turkishTrack, frenchTrack]
  };

  const ytEmitted = [];
  const ytCtx = {
    emit(event, payload) {
      ytEmitted.push(payload);
    },
    getSetting() {
      return true;
    }
  };

  const attached = await yt.DS.adaptorRegistry.attachBest(ytVideo, ytCtx);
  check('the YouTube adaptor wins on a YouTube page', attached && attached.adaptorId, 'youtube');

  const enPayload = ytEmitted.find((payload) => payload.kind === 'en');
  const trPayload = ytEmitted.find((payload) => payload.kind === 'tr');
  check('the manual English track beats the auto-generated one',
    enPayload.cues[0].text, 'Hello there.');
  check('the manual track source is reported', enPayload.source, 'youtube');
  check('the Turkish track is routed to Turkish', trPayload.cues[0].text, 'Merhaba.');
  check('the French track produced no channel',
    ytEmitted.some((payload) => /Bonjour/.test(payload.cues[0] && payload.cues[0].text)), false);
  check('the native English track was hidden', englishTrack.mode, 'hidden');

  // Cue changes are followed while the same track stays selected.
  englishTrack.cues.push({ startTime: 2, endTime: 4, text: 'Second line.' });
  englishTrack.fire('cuechange');
  const refreshed = ytEmitted.filter((payload) => payload.kind === 'en').pop();
  check('cue changes reach the overlay', refreshed.cues.length, 2);
  check('a cue change keeps the source label', refreshed.source, 'youtube');

  attached.detach();
  check('detach removes the cue listener', englishTrack.listenerCount('cuechange'), 0);

  // YouTube usually paints captions into its own DOM layer instead of exposing
  // TextTracks. The adaptor must claim the video and follow that text.
  const captionLayer = {
    text: 'I am learning English today.',
    querySelectorAll() {
      return [{ textContent: this.text }];
    }
  };
  captionLayer.innerText = captionLayer.text;

  const domDoc = {
    querySelector(selector) {
      return selector === '.ytp-caption-window-container' ? captionLayer : null;
    },
    documentElement: { classList: { add() {}, remove() {} } }
  };

  const ytDom = makeSandbox('www.youtube.com', domDoc);
  ytDom.load('adaptors/youtube.js');

  const domEmitted = [];
  const domCtx = {
    emit(event, payload) {
      domEmitted.push(payload);
    },
    getSetting() {
      return true;
    }
  };

  const domVideo = { textTracks: [], currentTime: 12 };
  const domAttached = await ytDom.DS.adaptorRegistry.attachBest(domVideo, domCtx);
  check('rendered YouTube captions are claimed (live adaptor)',
    domAttached && domAttached.adaptorId, 'youtube');

  await new Promise((resolve) => setTimeout(resolve, 400));
  const domPayload = domEmitted.find((payload) => payload.kind === 'en');
  checkTrue('the rendered caption text reaches the overlay',
    Boolean(domPayload && /learning English/.test(domPayload.cues[0].text)));
  check('the DOM capture is labelled', domPayload && domPayload.source, 'youtube-dom');

  // A Turkish caption line must go to the Turkish channel, not be translated
  // into Turkish on top of itself.
  captionLayer.text = 'Bugün İngilizce öğreniyorum.';
  captionLayer.innerText = captionLayer.text;
  await new Promise((resolve) => setTimeout(resolve, 400));
  const trDom = domEmitted.filter((payload) => payload.kind === 'tr').pop();
  checkTrue('a Turkish rendered line goes to the Turkish channel',
    Boolean(trDom && /İngilizce/.test(trDom.cues[0].text)));

  // Captions turned off must clear the overlay instead of freezing on the last
  // line.
  captionLayer.text = '';
  captionLayer.innerText = '';
  await new Promise((resolve) => setTimeout(resolve, 400));
  const lastDom = domEmitted[domEmitted.length - 1];
  check('turning captions off clears the line', lastDom && lastDom.cues.length, 0);

  if (domAttached) {
    domAttached.detach();
  }

  /* ---- live caption fragments become whole sentences ---- */

  // Reported bug: on YouTube the captions appeared word by word ("so", "so
  // today", "so today I'm...") because the visible fragment was published on
  // every repaint. A fragment must be assembled into a sentence and shown only
  // when that sentence is finished.
  const sentenceLayer = {
    text: 'so',
    querySelectorAll() {
      return [{ textContent: this.text }];
    }
  };
  sentenceLayer.innerText = sentenceLayer.text;

  const sentenceDoc = {
    querySelector(selector) {
      return selector === '.ytp-caption-window-container' ? sentenceLayer : null;
    },
    documentElement: { classList: { add() {}, remove() {} } }
  };

  const ytSentence = makeSandbox('www.youtube.com', sentenceDoc);
  ytSentence.load('adaptors/youtube.js');

  const sentenceEmitted = [];
  const sentenceCtx = {
    emit(event, payload) {
      if (event === 'cues') {
        sentenceEmitted.push(payload);
      }
    },
    getSetting() {
      return true;
    }
  };

  const sentenceVideo = { textTracks: [], currentTime: 5 };
  const sentenceAttached = await ytSentence.DS.adaptorRegistry.attachBest(
    sentenceVideo, sentenceCtx);

  await new Promise((resolve) => setTimeout(resolve, 320));
  check('a one-word fragment is not shown yet',
    sentenceEmitted.some((payload) => payload.cues.length &&
      payload.cues[0].text === 'so'), false);

  sentenceLayer.text = 'so today';
  sentenceLayer.innerText = sentenceLayer.text;
  await new Promise((resolve) => setTimeout(resolve, 320));
  check('a growing fragment is still not shown word by word',
    sentenceEmitted.some((payload) => payload.cues.length &&
      /^so today$/.test(payload.cues[0].text)), false);

  sentenceLayer.text = "so today I'm going to show you how it works.";
  sentenceLayer.innerText = sentenceLayer.text;
  await new Promise((resolve) => setTimeout(resolve, 400));

  const sentencePayload = sentenceEmitted.filter((payload) =>
    payload.kind === 'en' && payload.cues.length).pop();
  check('the finished sentence is shown in one piece',
    sentencePayload && sentencePayload.cues[0].text,
    "so today I'm going to show you how it works.");
  check('only the finished sentence was published',
    sentenceEmitted.filter((payload) => payload.kind === 'en' && payload.cues.length).length, 1);

  if (sentenceAttached) {
    sentenceAttached.detach();
  }

  /* ================= Netflix ================= */

  const nf = makeSandbox('www.netflix.com');
  nf.load('adaptors/netflix.js');

  const netflix = nf.DS.adaptors.netflix;
  check('Netflix is recognised', netflix.isNetflix(), true);

  // A real TextTrack must be left to the generic reader.
  const nfWithTracks = { textTracks: [makeTrack({ language: 'en', cues: [] })] };
  checkTrue('real tracks are detected', netflix.hasReadableTracks(nfWithTracks));
  check('a real track makes the DOM adaptor step aside',
    await nf.DS.adaptorRegistry.attachBest(nfWithTracks, { emit() {}, getSetting() { return true; } }),
    null);

  // Bitmap subtitles carry no text and must yield nothing.
  const bitmapDoc = {
    querySelector: () => ({ textContent: '' })
  };
  check('image-based subtitles read as empty', netflix.subtitleText(bitmapDoc), '');

  const textDoc = {
    querySelector: (selector) => (selector === '.player-timedtext'
      ? { textContent: '  Hello   there.  ' }
      : null)
  };
  check('rendered subtitle text is read and normalised',
    netflix.subtitleText(textDoc), 'Hello there.');

  // ---- live capture ----

  let clock = 0;
  let line = '';
  const emitted = [];

  const capture = netflix.createCapture({
    now: () => clock,
    read: () => line,
    emit: (payload) => emitted.push({ at: clock, payload: payload })
  });

  clock = 0;
  line = 'Hello there.';
  capture.tick();
  let last = emitted[emitted.length - 1].payload;
  check('a new line is shown immediately', last.kind, 'en');
  check('the open cue starts at the current time', last.cues[0].start, 0);
  checkTrue('the open cue extends into the future', last.cues[0].end > 0);
  const firstEnd = last.cues[0].end;

  clock = 1;
  capture.tick();
  last = emitted[emitted.length - 1].payload;
  checkTrue('a long line keeps being extended', last.cues[0].end > firstEnd);

  clock = 2;
  line = 'How are you?';
  capture.tick();
  last = emitted[emitted.length - 1].payload;
  check('a new line closes the previous one', last.cues.length, 2);
  check('the previous cue ends at the change', last.cues[0].end, 2);
  check('the new line is the open cue', last.cues[1].text, 'How are you?');

  clock = 4;
  line = '';
  capture.tick();
  last = emitted[emitted.length - 1].payload;
  check('a disappearing line is closed', last.cues.length, 2);
  check('the closing time is the current time', last.cues[1].end, 4);

  // Foreign dialogue is not filed under English.
  const beforeForeign = emitted.length;
  clock = 10;
  line = 'Quiero entender cada palabra.';
  capture.tick();
  clock = 11;
  line = '';
  capture.tick();
  check('Spanish lines produce no English cue', emitted.length, beforeForeign);

  // Turkish is recognised and routed to the Turkish channel.
  clock = 20;
  line = 'Merhaba, nasılsın?';
  capture.tick();
  last = emitted[emitted.length - 1].payload;
  check('a Turkish line goes to the Turkish channel', last.kind, 'tr');
  check('Turkish text is preserved', last.cues[0].text, 'Merhaba, nasılsın?');

  // ---- attach on a Netflix page ----

  const nfVideo = { currentTime: 0, textTracks: [] };
  const nfCtx = {
    emitted: [],
    emit(event, payload) {
      this.emitted.push(payload);
    },
    getSetting() {
      return true;
    }
  };

  const live = await nf.DS.adaptorRegistry.attachBest(nfVideo, nfCtx);
  check('the Netflix adaptor is accepted as a live adaptor',
    live && live.adaptorId, 'netflix');
  if (live) {
    live.detach();
  }

  console.log('');
  if (failures) {
    console.log(failures + ' adaptor check(s) failed.');
    process.exit(1);
  }
  console.log('All platform adaptor checks passed.');
})();
